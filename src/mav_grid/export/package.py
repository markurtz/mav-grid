"""Write the release files of a part (rule K-6): geometry, claim record, README.

A release folder holds everything people need to study, change and make a
part: STEP for CAD exchange, meshes ready to print, a flat cut map where a
sheet process can use one, the claim record (rule K-5), a build report and a
README that carries the claim line (rule K-2).
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from mav_grid.export.drawing import cut_map, write_dxf, write_svg
from mav_grid.export.solids import (
    write_3mf,
    write_glb,
    write_preview,
    write_step,
    write_stl,
)
from mav_grid.geometry.options import Options
from mav_grid.geometry.shapes import AssemblyPlan
from mav_grid.geometry.solid import BuiltAssembly, build_assembly
from mav_grid.schema.claims import claim_line
from mav_grid.schema.params import Params
from mav_grid.spec import HARDWARE_LICENCE, SPEC_VERSION
from mav_grid.version import __version__

__all__ = ["FORMATS", "SOLID_FORMATS", "Release", "write_release"]

SOLID_FORMATS = ("step", "stl", "3mf", "glb", "preview")
"""Formats that need the CAD kernel."""

FORMATS = (*SOLID_FORMATS, "svg", "dxf")
"""Every format :func:`write_release` can write."""

DEFAULT_FORMATS = ("step", "stl", "3mf", "preview")
FLAT_ROLES = ("plate",)
DISCLAIMER = (
    "Parts made to this spec by anyone other than the original designer are not "
    "endorsed or warrantied by them. Use is at your own risk."
)


@dataclass
class Release:
    """What :func:`write_release` wrote.

    :param folder: The release folder.
    :param files: Paths written, relative to the folder, with their role.
    :param record: The claim record as written.
    :param report: The build report as written.
    """

    folder: Path
    files: list[dict[str, str]] = field(default_factory=list)
    record: dict[str, Any] = field(default_factory=dict)
    report: dict[str, Any] = field(default_factory=dict)


def _changed_constants(params: Params) -> dict[str, dict[str, float]]:
    base = Params.load()
    return {
        name: {"spec": base.value(name), "used": entry.value}
        for name, entry in params.constants.items()
        if name in base.constants and base.value(name) != entry.value
    }


def _report(
    plan: AssemblyPlan, built: BuiltAssembly | None, params: Params, options: Options
) -> dict[str, Any]:
    parts = []
    for part in plan.parts:
        entry: dict[str, Any] = {
            "name": part.name,
            "role": part.role,
            "label": part.label,
            **part.meta,
        }
        if built is not None:
            solid = built.part(part.name)
            low, high = solid.bounds()
            entry["volume_mm3"] = round(solid.volume, 3)
            entry["bounds_mm"] = [[round(v, 4) for v in low], [round(v, 4) for v in high]]
            entry["valid"] = solid.is_valid
        parts.append(entry)
    return {
        "generator": f"mav-grid {__version__}",
        "spec_version": params.spec_version,
        "changed_constants": _changed_constants(params),
        "proposed_values": params.proposed(),
        "options": options.model_dump(),
        "parts": parts,
        "notes": plan.notes,
        "status": "Nothing in MAV Grid has been made or measured yet. Every fit "
        "is a calculation and is Unproven until its test passes.",
    }


def _readme(record: dict[str, Any], report: dict[str, Any], files: list[dict[str, str]]) -> str:
    changed = report["changed_constants"]
    lines = [
        f"# {record['name']}",
        "",
        f"`{record['claim_line']}`",
        "",
        f"Generated by {report['generator']} for MAV Grid {report['spec_version']}. "
        f"{report['status']}",
        "",
    ]
    if changed:
        lines += [
            "> **Not MAV Grid conforming.** These core values differ from the "
            "spec, so this part must not be called conforming (rule K-3):",
            ">",
            *[f"> - `{name}`: {v['used']:g} (spec {v['spec']:g})" for name, v in changed.items()],
            "",
        ]
    lines += ["## Files", "", "| File | Role |", "| :-- | :-- |"]
    lines += [f"| `{entry['path']}` | {entry['role']} |" for entry in files]
    lines += [
        "",
        "The claim record is the editable source: change it and run "
        "`mav-grid build` on it to regenerate every file.",
        "",
        "## Parts",
        "",
        "| Part | Role | Volume (mm³) |",
        "| :-- | :-- | --: |",
    ]
    for part in report["parts"]:
        volume = f"{part['volume_mm3']:.1f}" if "volume_mm3" in part else ""
        lines.append(f"| {part['name']} | {part['role']} | {volume} |")
    if report["notes"]:
        lines += ["", "## Notes", "", *[f"- {note}" for note in report["notes"]]]
    lines += [
        "",
        "## Licence",
        "",
        f"`{record.get('licence', HARDWARE_LICENCE)}`. {DISCLAIMER}",
        "",
    ]
    return "\n".join(lines)


def write_release(
    plan: AssemblyPlan,
    folder: Path | str,
    *,
    formats: Iterable[str] = DEFAULT_FORMATS,
    params: Params | None = None,
    options: Options | None = None,
) -> Release:
    """Write the release files of a planned record into a folder.

    Geometry file names carry the spec version (rule F-3). Reference parts
    (bought hardware, an existing surface) appear in the STEP, GLB and
    preview for context and get no mesh of their own.

    Example:
        .. code-block:: python

            import tempfile

            from mav_grid.export import write_release
            from mav_grid.generators import plan_plate

            plan = plan_plate(size="small", span=(1, 1))
            with tempfile.TemporaryDirectory() as folder:
                release = write_release(plan, folder, formats=["svg", "dxf"])
                assert (release.folder / "README.md").is_file()

    :param plan: The plan, with its claim record.
    :param folder: Folder to write into. It is created when missing.
    :param formats: Any of :data:`FORMATS`.
    :param params: The parameters the plan was made with.
    :param options: The options the plan was made with.
    :returns: What was written.
    :raises ValueError: For an unknown format or a plan without a record.
    """
    wanted = list(dict.fromkeys(formats))
    unknown = [name for name in wanted if name not in FORMATS]
    if unknown:
        raise ValueError(f"unknown format(s) {unknown} (known: {', '.join(FORMATS)})")
    if plan.record is None:
        raise ValueError("the plan carries no claim record")
    params = params or Params.load()
    options = options or Options()
    target = Path(folder)
    (target / "parts").mkdir(parents=True, exist_ok=True)
    stem = f"{plan.name}_{params.spec_version or SPEC_VERSION}"
    files: list[dict[str, str]] = []

    def wrote(path: Path, role: str) -> None:
        files.append({"path": path.relative_to(target).as_posix(), "role": role})

    built = build_assembly(plan) if any(f in SOLID_FORMATS for f in wanted) else None
    if built is not None:
        if "step" in wanted:
            wrote(write_step(built, target / f"{stem}.step"), "step")
        if "glb" in wanted:
            wrote(write_glb(built, target / f"{stem}.glb"), "other")
        if "preview" in wanted:
            wrote(write_preview(built, target / f"{stem}.preview.svg"), "drawing")
        for part in built.parts:
            if part.plan.role == "reference":
                continue
            if "stl" in wanted:
                wrote(write_stl(part, target / "parts" / f"{part.name}.stl"), "mesh")
            if "3mf" in wanted:
                wrote(write_3mf(part, target / "parts" / f"{part.name}.3mf"), "mesh")
    for part in plan.parts:
        if part.role not in FLAT_ROLES or len(part.sections) != 1:
            continue
        local = type(part)(part.name, part.role, [type(part.sections[0])(part.sections[0].ops)])
        drawing = cut_map(local)
        if "svg" in wanted:
            wrote(write_svg(drawing, target / "parts" / f"{part.name}.svg"), "drawing")
        if "dxf" in wanted:
            wrote(write_dxf(drawing, target / "parts" / f"{part.name}.dxf"), "drawing")
    if not any((target / "parts").iterdir()):
        (target / "parts").rmdir()

    record = dict(plan.record)
    record_path = target / f"{plan.name}.json"
    report_path = target / f"{plan.name}.build.json"
    wrote(target / "README.md", "readme")
    wrote(report_path, "other")
    record["files"] = files
    record["claim_line"] = claim_line(record, params=params.raw)
    report = _report(plan, built, params, options)
    record_path.write_text(
        json.dumps(record, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    report_path.write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    (target / "README.md").write_text(_readme(record, report, files), encoding="utf-8")
    return Release(folder=target, files=files, record=record, report=report)
